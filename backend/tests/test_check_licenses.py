"""scripts/check_licenses.py: the check of the dependencies against the project's licence policy."""

import importlib.util
import json
from pathlib import Path
from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "check_licenses.py"


@pytest.fixture(scope="module")
def checker() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_licenses", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.mark.parametrize(
    "licence",
    [
        "MIT",
        "MIT License",
        "BSD-3-Clause",
        "BSD License",
        "Apache-2.0",
        "Apache Software License",
        "ISC",
        "PSF-2.0",
        "Python Software Foundation License",
        "Unlicense",
        "0BSD",
        "Apache-2.0 OR BSD-3-Clause",
        "Apache-2.0 AND MIT",
        "(MIT OR GPL-3.0-or-later)",  # the user may choose the permissive one
        "BSD-3-Clause AND PSF-2.0",
    ],
)
def test_permissive_licences_pass(checker: ModuleType, licence: str) -> None:
    assert checker.classify(licence) == checker.OK, licence


@pytest.mark.parametrize(
    "licence",
    [
        "GPL-3.0",
        "GPL-3.0-or-later",
        "AGPL-3.0",
        "GNU General Public License v3",
        "SSPL-1.0",
        "MIT AND GPL-2.0",
    ],
)
def test_copyleft_licences_fail(checker: ModuleType, licence: str) -> None:
    """GPL and AGPL need the maintainer's approval, and "A AND B" is as bad as the worse."""
    assert checker.classify(licence) == checker.BAD, licence


@pytest.mark.parametrize(
    "licence",
    [
        "MPL-2.0",
        "LGPL-2.1",
        "GNU Lesser General Public License v3",
        "EPL-2.0",
        "CC-BY-4.0",
        "",
        "Proprietary",
        "see LICENSE",
    ],
)
def test_weak_copyleft_and_what_nobody_can_name_need_a_look(
    checker: ModuleType, licence: str
) -> None:
    assert checker.classify(licence) == checker.REVIEW, licence


def test_lgpl_is_not_taken_for_gpl(checker: ModuleType) -> None:
    """ "Lesser General Public License" contains "General Public License"."""
    assert checker.classify("LGPL-3.0-or-later") == checker.REVIEW
    assert checker.classify("GNU Lesser General Public License v2 (LGPLv2)") == checker.REVIEW


def test_names_are_read_from_a_uv_export_with_or_without_hashes(
    checker: ModuleType, tmp_path: Path
) -> None:
    export = tmp_path / "requirements.txt"
    export.write_text(
        "# This file was autogenerated by uv\n"
        "alembic==1.20.0 \\\n"
        "    --hash=sha256:abc\n"
        "annotated-doc==0.0.5\n"
        "    # via trafficpi\n"
        "SQLAlchemy==2.1.4 ; sys_platform == 'linux'\n"
    )
    assert checker.requirement_names(export) == ["alembic", "annotated-doc", "SQLAlchemy"]


def test_an_installed_package_says_what_its_licence_is(checker: ModuleType) -> None:
    assert checker.classify(checker.licence_of("fastapi")) == checker.OK
    assert checker.classify(checker.licence_of("psutil")) == checker.OK


def test_a_run_is_clean_when_everything_is_permissive_or_reviewed(
    checker: ModuleType, capsys: pytest.CaptureFixture[str]
) -> None:
    rows = [("fine", "MIT", checker.OK), ("certifi", "MPL-2.0", checker.REVIEW)]
    assert checker.report(rows) == 0  # certifi is on the reviewed list, with its reason
    said = capsys.readouterr().out
    assert "certifi" in said and "reviewed:" in said and "1 to look at" in said


def test_a_run_fails_for_a_licence_nobody_has_looked_at(
    checker: ModuleType, capsys: pytest.CaptureFixture[str]
) -> None:
    rows = [("fine", "MIT", checker.OK), ("newcomer", "GPL-3.0", checker.BAD)]
    assert checker.report(rows) == 1
    said = capsys.readouterr().out
    assert "newcomer" in said and "NOT REVIEWED" in said and "1 copyleft" in said


def test_every_reviewed_entry_says_why(checker: ModuleType) -> None:
    for name, reason in checker.REVIEWED.items():
        assert len(reason) > 30, name  # a reason, not a word
        assert "2026-" in reason, name  # dated, so that a reader knows when it was looked at


def test_the_pnpm_listing_is_read_as_licence_to_packages(
    checker: ModuleType, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    listing = {
        "MIT": [{"name": "react"}, {"name": "recharts"}],
        "GPL-3.0": [{"name": "something-else"}],
    }
    assert checker.check_pnpm(listing) == 1
    assert "something-else" in capsys.readouterr().out
    assert checker.check_pnpm({"MIT": [{"name": "react"}]}) == 0
    assert json.dumps(listing)  # (the shape is what `pnpm licenses list --json` prints)
